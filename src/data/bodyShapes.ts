// Contornos dos músculos sobre a ilustração (espaço 450x1151, eixo de simetria em x=225).
// Só o lado esquerdo da imagem é declarado; o direito sai por espelhamento no BodyMap.
// Cada ponto é [x, y] ou [x, y, 1]; o terceiro valor marca um canto vivo (sem suavizar),
// usado onde o contorno encosta no eixo central e precisa fechar reto.

export type Pt = [number, number] | [number, number, 1];

const f = (n: number) => Math.round(n * 10) / 10;

/** Spline Catmull-Rom fechada convertida em curvas de Bézier; cantos vivos têm tangente zero. */
export function smoothPath(pts: Pt[]): string {
  const n = pts.length;
  const at = (i: number) => pts[(i + n) % n];
  const corner = (p: Pt) => p.length === 3;
  let d = `M${f(pts[0][0])},${f(pts[0][1])}`;
  for (let i = 0; i < n; i++) {
    const p0 = at(i - 1);
    const p1 = at(i);
    const p2 = at(i + 1);
    const p3 = at(i + 2);
    const c1x = corner(p1) ? p1[0] : p1[0] + (p2[0] - p0[0]) / 6;
    const c1y = corner(p1) ? p1[1] : p1[1] + (p2[1] - p0[1]) / 6;
    const c2x = corner(p2) ? p2[0] : p2[0] - (p3[0] - p1[0]) / 6;
    const c2y = corner(p2) ? p2[1] : p2[1] - (p3[1] - p1[1]) / 6;
    d += ` C${f(c1x)},${f(c1y)} ${f(c2x)},${f(c2y)} ${f(p2[0])},${f(p2[1])}`;
  }
  return `${d} Z`;
}

