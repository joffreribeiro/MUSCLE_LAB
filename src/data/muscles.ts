export function getKinesiology(exerciseId: string): Kinesiology | null {
  return EXERCISE_KINESIOLOGY[exerciseId] ?? null;
}

export const itemName = (item: MuscleItem) => (typeof item === 'string' ? item : item.name);
export const itemDetail = (item: MuscleItem) => (typeof item === 'string' ? null : item.detail);
export const regionsOf = (item: MuscleItem): readonly MuscleKey[] => MUSCLE_REGIONS[itemName(item)];

/** Legenda — mesma ordem e cores usadas no mapa. */
export const roleBands: { role: MuscleRole; label: string; color: string }[] = [
  { role: 'primario', label: 'Primários', color: '#E8505B' },
  { role: 'secundario', label: 'Secundários', color: '#F2884B' },
  { role: 'estabilizador', label: 'Estabilizadores', color: '#F5C451' },
];

export const roleColor = (role: MuscleRole) => roleBands.find((b) => b.role === role)!.color;

const ROLE_LISTS: { role: MuscleRole; key: 'primarios' | 'secundarios' | 'estabilizadores' }[] = [
  { role: 'primario', key: 'primarios' },
  { role: 'secundario', key: 'secundarios' },
  { role: 'estabilizador', key: 'estabilizadores' },
];

/** Região → papel mais forte. Percorre do primário ao estabilizador e não sobrescreve. */
export function regionRoles(k: Kinesiology): RegionRoles {
  const out: RegionRoles = {};
  for (const { role, key } of ROLE_LISTS) {
    for (const item of k[key]) {
      for (const region of regionsOf(item)) out[region] ??= role;
    }
  }
  return out;
}

export function roleGroups(k: Kinesiology) {
  return ROLE_LISTS.map(({ role, key }) => ({
    role,
    label: roleBands.find((b) => b.role === role)!.label,
    items: k[key],
  })).filter((g) => g.items.length > 0);
}
